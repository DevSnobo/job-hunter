CREATE TABLE applications (
    -- UUID generated by tooling; also used as the stable artifact-directory name.
    id TEXT PRIMARY KEY CHECK (length(trim(id)) > 0),
    company TEXT NOT NULL CHECK (length(trim(company)) > 0),
    role TEXT NOT NULL CHECK (length(trim(role)) > 0),
    -- This field IS the submission event. Do not duplicate it in events.
    submitted_on TEXT NOT NULL CHECK (
        length(submitted_on) = 10 AND date(submitted_on, '+0 days') IS NOT NULL
        AND date(submitted_on, '+0 days') = submitted_on
    ),
    discovery_source TEXT NOT NULL DEFAULT 'unknown' REFERENCES discovery_sources(code),
    submission_channel TEXT NOT NULL DEFAULT 'unknown' REFERENCES submission_channels(code),
    recruiter_type TEXT NOT NULL DEFAULT 'unknown' REFERENCES recruiter_types(code),
    platform_name TEXT, -- Optional: Workday, Personio, Greenhouse, etc.
    source_detail TEXT, -- Specific job board/referral, if useful.
    job_url TEXT,
    location TEXT,
    notes TEXT,
    created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
) STRICT;

CREATE TABLE rounds (
    id INTEGER PRIMARY KEY,
    application_id TEXT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    -- Stable within an application. Includes screens/assessments, not a chart counter.
    sequence_no INTEGER NOT NULL CHECK (sequence_no > 0),
    phase TEXT NOT NULL CHECK (phase IN ('screening', 'interview', 'assessment')),
    round_type TEXT NOT NULL REFERENCES round_types(code),
    format TEXT NOT NULL DEFAULT 'unknown' REFERENCES interview_formats(code),
    label TEXT,
    notes TEXT,
    created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    UNIQUE (application_id, sequence_no),
    UNIQUE (application_id, id)
) STRICT;

-- One interview can include both a manager and team members.
CREATE TABLE round_participants (
    round_id INTEGER NOT NULL REFERENCES rounds(id) ON DELETE CASCADE,
