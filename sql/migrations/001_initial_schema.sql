CREATE TRIGGER events_validate_insert BEFORE INSERT ON events BEGIN
    SELECT RAISE(ABORT, 'Event predates application submission')
    WHERE NEW.occurred_on < (SELECT submitted_on FROM applications WHERE id = NEW.application_id);
    SELECT RAISE(ABORT, 'Event type has incompatible round scope')
    WHERE EXISTS (SELECT 1 FROM event_types WHERE code = NEW.event_type AND
        ((scope = 'round' AND NEW.round_id IS NULL) OR (scope = 'application' AND NEW.round_id IS NOT NULL)));
    SELECT RAISE(ABORT, 'Assessment event requires assessment phase; completed requires interview/screening')
    WHERE EXISTS (SELECT 1 FROM rounds WHERE id = NEW.round_id AND
        ((NEW.event_type IN ('assessment_received', 'assessment_submitted') AND phase != 'assessment')
        OR (NEW.event_type = 'completed' AND phase = 'assessment')));
END;
CREATE TRIGGER events_validate_update BEFORE UPDATE ON events BEGIN
    SELECT RAISE(ABORT, 'Event predates application submission')
    WHERE NEW.occurred_on < (SELECT submitted_on FROM applications WHERE id = NEW.application_id);
    SELECT RAISE(ABORT, 'Event type has incompatible round scope')
    WHERE EXISTS (SELECT 1 FROM event_types WHERE code = NEW.event_type AND
        ((scope = 'round' AND NEW.round_id IS NULL) OR (scope = 'application' AND NEW.round_id IS NOT NULL)));
    SELECT RAISE(ABORT, 'Assessment event requires assessment phase; completed requires interview/screening')
    WHERE EXISTS (SELECT 1 FROM rounds WHERE id = NEW.round_id AND
        ((NEW.event_type IN ('assessment_received', 'assessment_submitted') AND phase != 'assessment')
        OR (NEW.event_type = 'completed' AND phase = 'assessment')));
END;
CREATE TRIGGER applications_validate_submission_update BEFORE UPDATE OF submitted_on ON applications BEGIN
    SELECT RAISE(ABORT, 'Submission would fall after existing events')
    WHERE EXISTS (SELECT 1 FROM events WHERE application_id = OLD.id AND occurred_on < NEW.submitted_on);
END;
CREATE TRIGGER rounds_validate_phase_update BEFORE UPDATE OF phase ON rounds BEGIN
    SELECT RAISE(ABORT, 'Round phase conflicts with existing completion/assessment events')
    WHERE EXISTS (SELECT 1 FROM events WHERE round_id = OLD.id AND
        ((event_type IN ('assessment_received', 'assessment_submitted') AND NEW.phase != 'assessment')
        OR (event_type = 'completed' AND NEW.phase = 'assessment')));
END;

