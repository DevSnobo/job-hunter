CREATE TABLE events (
    id INTEGER PRIMARY KEY,
    application_id TEXT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    round_id INTEGER,
    event_type TEXT NOT NULL REFERENCES event_types(code),
    occurred_on TEXT NOT NULL CHECK (
        length(occurred_on) = 10 AND date(occurred_on, '+0 days') IS NOT NULL
        AND date(occurred_on, '+0 days') = occurred_on
    ),
    -- Explicit order avoids confusing late entry with actual event order.
    day_order INTEGER NOT NULL CHECK (day_order > 0),
    -- Schedule payload is stored on each scheduling event, preserving reschedules.
    scheduled_for TEXT CHECK (
        scheduled_for IS NULL OR (length(scheduled_for) = 10
        AND date(scheduled_for, '+0 days') IS NOT NULL
        AND date(scheduled_for, '+0 days') = scheduled_for)
    ),
    scheduled_time TEXT CHECK (
        scheduled_time IS NULL OR (length(scheduled_time) = 5
        AND scheduled_time GLOB '[0-2][0-9]:[0-5][0-9]'
        AND substr(scheduled_time, 1, 2) <= '23')
    ),
    timezone TEXT, -- IANA name, validated by the CLI (e.g. Europe/Berlin).
    reason_code TEXT, -- Optional short tag; free text belongs in notes.
    notes TEXT,
    recorded_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    FOREIGN KEY (application_id, round_id)
        REFERENCES rounds(application_id, id) ON DELETE CASCADE,
    UNIQUE (application_id, occurred_on, day_order),
    CHECK (
        (event_type IN ('scheduled', 'rescheduled') AND scheduled_for IS NOT NULL)
        OR (event_type NOT IN ('scheduled', 'rescheduled') AND scheduled_for IS NULL
            AND scheduled_time IS NULL AND timezone IS NULL)
    ),
    CHECK ((scheduled_time IS NULL AND timezone IS NULL)
        OR (scheduled_time IS NOT NULL AND timezone IS NOT NULL AND length(trim(timezone)) > 0)),
    CHECK (scheduled_for IS NULL OR scheduled_for >= occurred_on)
) STRICT;

-- A round has one completion, even if invitation/scheduling events repeat.
CREATE UNIQUE INDEX one_completion_per_round ON events(round_id)
    WHERE event_type IN ('completed', 'assessment_submitted');
